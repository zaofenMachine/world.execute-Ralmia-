"""Lock role_m's fixed regions to role_s after AI-local-edit generation.

Uses the user's existing authorization for restoring A pixels outside local edits.
Source art is generated by image_gen; this script does not draw character details.
"""
from pathlib import Path
import json,hashlib,shutil
import numpy as np
from PIL import Image,ImageDraw,ImageFilter,ImageFont

ROOT=Path(__file__).resolve().parents[2]
RAW=ROOT/'_production'/'round3'/'raw'
QA=ROOT/'_qa'/'round3'
RAW.mkdir(parents=True,exist_ok=True)
QA.mkdir(parents=True,exist_ok=True)
NAMES=['cat_ralmia.png','role_s.png','role_m.png']
other_hashes={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in ROOT.glob('*.png') if p.name not in NAMES}
raw_b=RAW/'role_m_ai.png'
if not raw_b.exists():
    shutil.copy2(ROOT/'role_m.png',raw_b)
a=np.array(Image.open(ROOT/'role_s.png').convert('RGBA'))
b=np.array(Image.open(raw_b).convert('RGBA'))
assert a.shape==b.shape,(a.shape,b.shape)
h,w=a.shape[:2]
mask_im=Image.new('L',(w,h),0)
d=ImageDraw.Draw(mask_im)
polygons=[
    # Internal facial expression; hair silhouette, gem and outer jaw stay in A.
    [(743,313),(790,281),(861,265),(932,276),(955,326),(945,401),(916,437),(878,457),(820,444),(771,423),(744,389)],
    # Left-on-screen old hip arm and new inward clasp arm, plus revealed areas.
    [(401,620),(476,550),(648,477),(723,476),(804,520),(858,492),(934,487),
     (973,584),(927,681),(865,746),(816,832),(788,940),(583,940),(382,765),(379,669)],
    # Right-on-screen old mouth hand and arm / new clasp arm.
    [(890,381),(974,391),(1055,469),(1180,550),(1280,870),(1073,925),
     (961,793),(909,705),(869,613),(868,494)],
]
for p in polygons:
    d.polygon([(round(x*w/1672),round(y*h/941)) for x,y in p],fill=255)
mask=np.array(mask_im)
weight=np.array(mask_im.filter(ImageFilter.GaussianBlur(4)),dtype=float)/255
weight*=mask>0

def gold(im):
    v=im.astype(int)
    return (v[:,:,0]-v[:,:,2]>95)&(v[:,:,1]-v[:,:,2]>55)&(v[:,:,1]>105)&(v[:,:,2]<155)&(v[:,:,3]>128)
yy,xx=np.indices((h,w))
protect=gold(a)&gold(b)&(yy<480)
# Original waist/low torso is a rigid anchor, outside any changed hands.
protect|=(xx>=840)&(xx<=950)&(yy>=870)
# Temple gem, forehead/ahoge and head-outline anchors explicitly fixed.
protect|=(xx>=670)&(xx<=750)&(yy>=180)&(yy<=307)
protect|=(yy<260)
weight[protect]=0
mask[protect]=0
out=np.rint(a*(1-weight[:,:,None])+b*weight[:,:,None]).clip(0,255).astype('uint8')
Image.fromarray(out).save(ROOT/'role_m.png')
Image.fromarray(mask).save(QA/'role_edit_mask.png')
outside=mask==0
changed=np.any(a!=out,axis=2)
assert not changed[outside].any()
for region in [(670,180,750,307),(650,0,1000,260),(840,870,951,941)]:
    x0,y0,x1,y1=region
    assert np.array_equal(a[y0:y1,x0:x1],out[y0:y1,x0:x1]),region
pair={'base':'role_s.png','edit':'role_m.png','generation':'image_gen local edit with A and ref_sheet as inputs',
      'postprocess':'authorized original-pixel restoration outside face/hand/arm masks',
      'canvas':[w,h],'outside_edit_pixels':int(outside.sum()),'outside_edit_changed_pixels':0,
      'outside_edit_exact_match_percent':100.0,
      'fixed_gem_forehead_ahoge_and_waist_verified':True,
      'allowed_changes':['facial expression, blush, eye-corner gleam','hands and arms, including inward shoulder gesture','areas revealed/occluded by changed limbs']}

assets=[]
for name in NAMES:
    im=Image.open(ROOT/name)
    assert im.mode=='RGBA',name
    al=np.array(im.getchannel('A'))
    assert al.min()==0 and al.max()==255,name
    solid=Image.fromarray((al>32).astype('uint8')*255).getbbox()
    assets.append({'file':name,'size':list(im.size),'mode':im.mode,'bytes':(ROOT/name).stat().st_size,
                   'alpha_range':[int(al.min()),int(al.max())],
                   'alpha_gt_32_bbox':solid,'visible_width_fraction':round((solid[2]-solid[0])/im.width,4)})
for name,digest in other_hashes.items():
    assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==digest,name

font=ImageFont.truetype('C:/Windows/Fonts/consola.ttf',22)
sheet=Image.new('RGB',(1500,337),'#25272b')
draw=ImageDraw.Draw(sheet)
for i,name in enumerate(NAMES):
    im=Image.open(ROOT/name).convert('RGBA')
    bg=Image.new('RGBA',im.size,'#55575d')
    bg.alpha_composite(im)
    bg.thumbnail((500,281),Image.Resampling.LANCZOS)
    sheet.paste(bg.convert('RGB'),(500*i,0))
    draw.text((500*i+12,291),name,font=font,fill='#eeeeee')
sheet.save(QA/'contact_sheet.jpg',quality=95)
frames=[]
for data in [a,out]:
    im=Image.fromarray(data)
    bg=Image.new('RGBA',im.size,'#30353e')
    bg.alpha_composite(im)
    frames.append(bg.convert('RGB').resize((836,470),Image.Resampling.LANCZOS))
palette_source=Image.new('RGB',(1672,470))
palette_source.paste(frames[0],(0,0))
palette_source.paste(frames[1],(836,0))
palette=palette_source.quantize(colors=256)
indexed=[im.quantize(palette=palette,dither=Image.Dither.NONE) for im in frames]
indexed[0].save(QA/'role_switch.gif',save_all=True,append_images=indexed[1:],duration=550,loop=0,optimize=False)
indexed[0].save(QA/'role_switch_fast.gif',save_all=True,append_images=indexed[1:],duration=120,loop=0,optimize=False)
report={'scope':'3 P0 images, request_round3; run_front_b withdrawn','assets':assets,'pair':pair,
        'other_final_pngs_verified_unchanged':len(other_hashes),
        'native_resolution_note':'Native files approximately 1672x941; no upscaling to claim 2560x1440.'}
(QA/'validation.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(report,ensure_ascii=False,indent=2))
